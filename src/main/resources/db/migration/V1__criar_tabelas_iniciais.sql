CREATE TABLE grupo_convite (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(100) NOT NULL UNIQUE,
    nome_exibicao VARCHAR(150)
);

CREATE TABLE convidado (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grupo_convite_id INTEGER NOT NULL,
    nome VARCHAR(150) NOT NULL,
    presenca VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    data_confirmacao TIMESTAMP,

    CONSTRAINT fk_convidado_grupo
        FOREIGN KEY (grupo_convite_id)
        REFERENCES grupo_convite (id),

    CONSTRAINT chk_convidado_presenca
        CHECK (presenca IN ('PENDENTE', 'CONFIRMADO', 'RECUSADO'))
);

CREATE INDEX idx_convidado_grupo_convite
    ON convidado (grupo_convite_id);


CREATE TABLE presente (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    categoria VARCHAR(100) NOT NULL,
    recebido BOOLEAN NOT NULL DEFAULT FALSE,
    ordem INTEGER NOT NULL
);

CREATE INDEX idx_presente_ordem
    ON presente (ordem);

